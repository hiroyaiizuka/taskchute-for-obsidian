import esbuild from "esbuild";
import process from "process";
import fs from "fs";
import path from "path";
// Use Node's built-in modules list to avoid JSON import assertions incompatibility
import { builtinModules as nodeBuiltinModules } from "module";
import { execFileSync } from "child_process";

const banner =
`/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin
*/
`;

const prod = (process.argv[2] === "production");

// Optional dev target: write the build artifacts straight into an Obsidian
// vault's plugin folder instead of the repository root. Pointed at a vault in
// iCloud Drive, that is what puts a change on an iPhone or iPad without
// cutting a release. `npm run dev` reads OBSIDIAN_PLUGIN_DIR out of `.env`
// (see AGENTS.md); a production build ignores it outright, so a release
// artifact always lands at the repository root no matter what the shell holds.
const pluginDir = prod ? null : process.env.OBSIDIAN_PLUGIN_DIR?.trim() || null;
if (pluginDir && !fs.existsSync(pluginDir)) {
	throw new Error(`OBSIDIAN_PLUGIN_DIR does not exist: ${pluginDir}`);
}

// `manifest.json` and `styles.css` are not part of the esbuild graph, so copy
// them alongside every rebuild; otherwise a CSS-only edit never reaches the vault.
const copyStaticAssets = {
	name: "copy-static-assets",
	setup(build) {
		build.onEnd((result) => {
			if (!pluginDir || result.errors.length > 0) return;
			for (const file of ["manifest.json", "styles.css"]) {
				fs.copyFileSync(file, path.join(pluginDir, file));
			}
		});
	},
};

// The build number shown after the version in settings, "2.2.16 (614)": the
// number of commits in the history being built. It only ever goes up.
//
// A release build has to come out byte for byte the same from the tagged
// commit alone, because Obsidian's plugin review rebuilds the release from a
// clone of the tag and compares the result with the main.js attached to it
// (3.0.6 was flagged "Build output does not match the released main.js": the
// review's clone is shallow, so it counted 0 commits where the release had
// counted 714). So a production build reads the number from build-number.json,
// which the release workflow writes into the release commit. A dev build counts
// the commits itself, and TASKCHUTE_BUILD_NUMBER overrides both (the beta
// workflow sets it, since a beta is never committed). Without git, or in a
// shallow clone, a dev build's number is 0. It is a virtual module rather than
// a `define` so `npm run dev` recomputes it on every rebuild.
function git(args) {
	try {
		return execFileSync("git", args, { encoding: "utf8", stdio: ["ignore", "pipe", "ignore"] }).trim();
	} catch {
		return "";
	}
}

function buildNumber() {
	const fromEnv = Number(process.env.TASKCHUTE_BUILD_NUMBER);
	if (Number.isInteger(fromEnv) && fromEnv > 0) return fromEnv;
	if (prod) {
		const recorded = JSON.parse(fs.readFileSync("build-number.json", "utf8")).number;
		return Number.isInteger(recorded) && recorded > 0 ? recorded : 0;
	}
	const shallow = git(["rev-parse", "--is-shallow-repository"]) === "true";
	return shallow ? 0 : Number(git(["rev-list", "--count", "HEAD"])) || 0;
}

const buildInfoModule = {
	name: "build-info",
	setup(build) {
		build.onResolve({ filter: /^taskchute:build-info$/ }, (args) => ({ path: args.path, namespace: "build-info" }));
		build.onLoad({ filter: /.*/, namespace: "build-info" }, () => {
			const info = { number: buildNumber() };
			return { contents: `export default ${JSON.stringify(info)};`, loader: "js" };
		});
	},
};

const context = await esbuild.context({
	banner: {
		js: banner,
	},
	entryPoints: ["src/main.ts"],
	bundle: true,
	external: [
		"obsidian",
		"electron",
		"@codemirror/autocomplete",
		"@codemirror/collab",
		"@codemirror/commands",
		"@codemirror/language",
		"@codemirror/lint",
		"@codemirror/search",
		"@codemirror/state",
		"@codemirror/view",
		"@lezer/common",
		"@lezer/highlight",
    "@lezer/lr",
    ...nodeBuiltinModules
	],
	format: "cjs",
	target: "es2018",
	logLevel: "info",
	// Minify production builds. The unminified bundle exceeds the size/AST
	// limits of several static-analysis and malware scanners, which then skip
	// the file instead of reporting a result.
	minify: prod,
	// The inline sourcemap makes the dev bundle ~10MB. That is fine on disk but
	// wasteful when every rebuild is pushed through Obsidian Sync to a phone or
	// tablet, so vault-targeted builds ship without it.
	sourcemap: (prod || pluginDir) ? false : "inline",
	treeShaking: true,
	outfile: pluginDir ? path.join(pluginDir, "main.js") : "main.js",
	plugins: pluginDir ? [buildInfoModule, copyStaticAssets] : [buildInfoModule],
});

if (prod) {
	await context.rebuild();
	process.exit(0);
} else {
	await context.watch();
}
